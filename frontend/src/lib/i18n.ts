export function getTranslation(
  lang: string | undefined,
  key: string,
  fallbackOrParams?: string | Record<string, any>,
  params?: Record<string, any>
): string {
  const code = (lang || 'ta').toLowerCase() as LanguageCode;
  const dict = TRANSLATIONS[code] || TRANSLATIONS['ta'] || TRANSLATIONS['en'];

  let fallback: string | undefined;
  let interpolations: Record<string, any> | undefined;

  if (typeof fallbackOrParams === 'object' && fallbackOrParams !== null) {
    interpolations = fallbackOrParams;
    fallback = undefined;
  } else {
    fallback = fallbackOrParams;
    interpolations = params;
  }

  let text: string | undefined = dict?.[key];

  if (!text) {
    const enDict = TRANSLATIONS['en'];
    text = enDict?.[key];
  }

  if (!text) {
    text = fallback || key;
  }

  if (interpolations && typeof text === 'string') {
    for (const [k, v] of Object.entries(interpolations)) {
      text = text.split(`{${k}}`).join(String(v));
      text = text.split(`{{${k}}}`).join(String(v));
    }
  }

  return text;
}
