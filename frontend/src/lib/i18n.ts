export function getTranslation(lang: string | undefined, key: string, fallback?: string): string {
  const code = (lang || 'ta').toLowerCase() as LanguageCode;
  const dict = TRANSLATIONS[code] || TRANSLATIONS['ta'] || TRANSLATIONS['en'];
  if (dict && dict[key]) {
    return dict[key];
  }
  const enDict = TRANSLATIONS['en'];
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return fallback || key;
}
